#include<bits/stdc++.h>
using namespace std;

int main()
{
    int x = 5;
    cout<<"Initial values of x:"<<x<<endl;
    cout<<"Value printed during x++:"<<x++<<endl;
    cout<<"Value printed after x++:"<<x<<endl;

    x = 5;
    cout<<"Value printed during ++x:"<<++x<<endl;
    cout<<"Value printed after ++x:"<<x<<endl;

    return 0;

}